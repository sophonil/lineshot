import AppKit
import XCTest
@testable import Tendedero

final class TextClippingTests: XCTestCase {
    private func temporaryFolder() throws -> URL {
        let folder = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: folder) }
        return folder
    }

    func testUTF8RoundTripAndPrivatePermissions() throws {
        let text = "  中文 🧺\nlet value = 42\t\nمرحبا\r\n"
        let folder = try temporaryFolder()
        let url = try TextClipping.save(text, in: folder)
        XCTAssertEqual(TextClipping.read(url), text)
        let attrs = try FileManager.default.attributesOfItem(atPath: url.path)
        XCTAssertEqual((attrs[.posixPermissions] as? NSNumber)?.intValue, 0o600)
        XCTAssertFalse(url.lastPathComponent.contains("value"))
        let second = try TextClipping.save(text, in: folder)
        XCTAssertNotEqual(url, second)
    }

    func testBlankAndOversizedTextAreRejected() throws {
        let folder = try temporaryFolder()
        for text in ["", " \n\t\r", String(repeating: "中", count: TextClipping.maxBytes / 3 + 1)] {
            XCTAssertFalse(TextClipping.accepts(text))
            XCTAssertThrowsError(try TextClipping.save(text, in: folder))
        }
        XCTAssertTrue(TextClipping.accepts(String(repeating: "a", count: TextClipping.maxBytes)))
        XCTAssertTrue(try FileManager.default.contentsOfDirectory(atPath: folder.path).isEmpty)
    }

    func testOversizedFileIsNotRead() throws {
        let url = try temporaryFolder().appendingPathComponent("large.txt")
        try Data(repeating: 65, count: TextClipping.maxBytes + 1).write(to: url)
        XCTAssertNil(TextClipping.read(url))
    }

    func testIndependentTogglesAndRichTextPreference() async {
        await MainActor.run {
            let item = NSPasteboardItem()
            item.setString("  copied text\n", forType: .string)
            item.setData(Data([1, 2, 3]), forType: .png)
            XCTAssertNil(ClipboardWatcher.content(from: [item], images: false, text: false))
            // Turning text off must not turn rich text's image fallback into a photo.
            XCTAssertNil(ClipboardWatcher.content(from: [item], images: true, text: false))
            for images in [false, true] {
                guard case .text(let value) = ClipboardWatcher.content(from: [item], images: images, text: true) else {
                    return XCTFail("Text should win over the image representation")
                }
                XCTAssertEqual(value, "  copied text\n")
            }
        }
    }

    func testImageCaptureStillWorksIndependently() async {
        await MainActor.run {
            let item = NSPasteboardItem(), bytes = Data([1, 2, 3])
            item.setData(bytes, forType: .png)
            XCTAssertNil(ClipboardWatcher.content(from: [item], images: false, text: true))
            guard case .image(let data, let type) = ClipboardWatcher.content(from: [item], images: true, text: false) else {
                return XCTFail("Image capture should still be available")
            }
            XCTAssertEqual(data, bytes)
            XCTAssertEqual(type, .png)
        }
    }

    func testPrivacyMarkersBlockTheWholeClipboard() async {
        await MainActor.run {
            for type in [NSPasteboard.PasteboardType.fileURL, TextClipping.pasteboardType,
                         .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
                         .init("org.nspasteboard.AutoGeneratedType")] {
                let text = NSPasteboardItem(), marker = NSPasteboardItem()
                text.setString("Sensitive text", forType: .string)
                marker.setString("1", forType: type)
                XCTAssertNil(ClipboardWatcher.content(from: [text, marker], images: true, text: true))
            }
        }
    }

    func testCopyAndDragPreserveFullTextWithoutRecapture() async throws {
        let text = String(repeating: "完整文本\n", count: 600)
        let url = try TextClipping.save(text, in: temporaryFolder())
        await MainActor.run {
            guard let copy = TextClipping.pasteboardItem(for: url),
                  let drag = TextClipping.pasteboardItem(for: url, includeFile: true) else { return XCTFail() }
            XCTAssertEqual(copy.string(forType: .string), text)
            XCTAssertNil(copy.string(forType: .fileURL))
            XCTAssertEqual(drag.string(forType: .string), text)
            XCTAssertEqual(drag.string(forType: .fileURL), url.absoluteString)
            XCTAssertNil(ClipboardWatcher.content(from: [copy], images: true, text: true))
            XCTAssertNil(ClipboardWatcher.content(from: [drag], images: true, text: true))
        }
    }

    func testTextRestoresOnTheLineAndMissingFilesArePruned() async throws {
        let text = "A clipping to restore\n恢复后的文本"
        let url = try TextClipping.save(text, in: temporaryFolder())
        try await MainActor.run {
            let suite = "TendederoTests.\(UUID().uuidString)"
            let defaults = UserDefaults(suiteName: suite)!
            defer { defaults.removePersistentDomain(forName: suite) }
            let line = Line(defaults: defaults)
            XCTAssertNotNil(line.hang(url, quietly: true))
            XCTAssertNil(line.hang(url, quietly: true))
            XCTAssertEqual(line.liveCount, 1)
            let restored = Line(defaults: defaults)
            XCTAssertEqual(restored.items.count, 1)
            XCTAssertTrue(restored.items[0].isText)
            XCTAssertEqual(TextClipping.read(restored.items[0].url), text)
            try FileManager.default.removeItem(at: url)
            restored.prune()
            XCTAssertEqual(restored.liveCount, 0)
            XCTAssertTrue(Line(defaults: defaults).items.isEmpty)
        }
    }

    func testThumbnailRendersWithoutShorteningStoredText() async throws {
        let text = String(repeating: "保持原有风格 · Keep it simple 🧺\n", count: 200)
        let url = try TextClipping.save(text, in: temporaryFolder())
        await MainActor.run {
            for pixels in [256, 320, 432] {
                let image = TextClipping.thumbnail(url, maxPixels: pixels)
                XCTAssertEqual(image?.size.width, CGFloat(pixels))
                XCTAssertNotNil(image?.cgImage(forProposedRect: nil, context: nil, hints: nil))
            }
            XCTAssertEqual(TextClipping.read(url), text)
        }
    }
}
